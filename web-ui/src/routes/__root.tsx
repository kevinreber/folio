import { createRootRouteWithContext, Link, Outlet } from "@tanstack/react-router";
import { useQuery } from "@tanstack/react-query";
import type { QueryClient } from "@tanstack/react-query";
import { healthQuery } from "../api/queries";

interface RouterContext {
  queryClient: QueryClient;
}

export const rootRoute = createRootRouteWithContext<RouterContext>()({
  component: RootLayout,
});

function RootLayout() {
  const health = useQuery(healthQuery);
  const connected = health.isSuccess;

  return (
    <div id="app">
      <nav id="sidebar">
        <div className="sidebar-header">
          <h1 className="logo">folio</h1>
          <span className="logo-tagline">career tracker</span>
        </div>
        <ul className="nav-links">
          <NavItem to="/" label="Dashboard" icon={<DashboardIcon />} />
          <NavItem to="/activities" label="Activities" icon={<ActivitiesIcon />} />
          <NavItem to="/search" label="Search" icon={<SearchIcon />} />
          <NavItem to="/timeline" label="Timeline" icon={<TimelineIcon />} />
          <NavItem to="/accomplishments" label="Accomplish" icon={<AccomplishIcon />} />
          <NavItem to="/claude" label="Claude" icon={<ClaudeIcon />} />
          <NavItem to="/capture" label="Capture" icon={<CaptureIcon />} />
          <NavItem to="/whatsnew" label="What's New" icon={<WhatsNewIcon />} />
          <NavItem to="/setup" label="Setup" icon={<SetupIcon />} />
        </ul>
        <div className="sidebar-footer">
          <div className={`status-dot ${connected ? "connected" : "disconnected"}`} />
          <span>{connected ? "API Connected" : "Disconnected"}</span>
        </div>
      </nav>
      <main id="content">
        <Outlet />
      </main>
    </div>
  );
}

function NavItem({ to, label, icon }: { to: string; label: string; icon: React.ReactNode }) {
  return (
    <li>
      <Link
        to={to}
        className="nav-link"
        activeProps={{ className: "nav-link active" }}
        activeOptions={{ exact: to === "/" }}
      >
        {icon}
        {label}
      </Link>
    </li>
  );
}

